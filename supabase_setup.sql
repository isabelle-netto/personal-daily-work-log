-- The app uses a server-only secret key; no browser-side database credentials.
create table if not exists public.work_tasks (
    id bigint generated by default as identity primary key,
    task_date date not null,
    task text not null check (length(trim(task)) > 0),
    status text not null default 'Pending' check (status in ('Pending', 'Completed', 'Not Completed')),
    remark text not null default '',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.work_tasks enable row level security;
-- No anon/authenticated access policies: public clients cannot read/write.
-- Only the server-side Supabase secret/service_role key can access the table.

create or replace function public.work_tasks_update_timestamp()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists work_tasks_timestamp on public.work_tasks;
create trigger work_tasks_timestamp before update on public.work_tasks
for each row execute function public.work_tasks_update_timestamp();
